-- Smart Learning database schema (PostgreSQL 14 or later).
-- The backend runs this on every start (lib/db.js), and it is safe to re-run: every statement
-- is CREATE ... IF NOT EXISTS. You can also run it yourself in pgAdmin (Query Tool, then
-- Execute) after creating the smart_learning database.
--
-- Times are TIMESTAMPTZ and kept in UTC. Yes/no flags are SMALLINT (1 or 0), as the code
-- reads and writes them.

-- every account; the role decides which of the role-specific columns are used
CREATE TABLE IF NOT EXISTS users (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(100) NOT NULL,
  email VARCHAR(254) NULL UNIQUE,  -- learners have none: they log in with their learner number
  role VARCHAR(10) NOT NULL CHECK (role IN ('learner','teacher','parent','hod','principal','admin')),
  password_hash VARCHAR(100) NOT NULL,
  must_change_password SMALLINT NOT NULL DEFAULT 0,  -- 1 while on an administrator-issued temporary password
  token_version INT NOT NULL DEFAULT 0,              -- bumped on password change: logs out older sessions
  failed_logins INT NOT NULL DEFAULT 0,              -- wrong passwords (or sign-in codes) in a row
  locked_until TIMESTAMPTZ NULL,                     -- set after too many of them: no sign-in until then
  phone VARCHAR(30) NULL,
  grade VARCHAR(4) NULL,            -- learner: the grade they are in
  class_name VARCHAR(10) NULL,      -- learner: their register class, e.g. 10A (they join its subject classes)
  learner_number VARCHAR(30) NULL UNIQUE,  -- learner: the number the school gave them (admission number), used to log in
  progress INT NOT NULL DEFAULT 0,  -- learner: overall progress this term (%)
  subject_key VARCHAR(60) NULL,     -- teacher: the subject they teach
  teach_grade VARCHAR(4) NULL,      -- teacher: the grade they mainly teach
  staff_number VARCHAR(30) NULL,    -- teacher
  dept VARCHAR(30) NULL,            -- teacher (from their subject) and HOD (the department they lead)
  attendance INT NULL,              -- teacher: attendance (%)
  performance INT NULL,             -- teacher: class performance (%)
  work_done SMALLINT NULL,          -- teacher: assigned interventions done? NULL = not asked yet
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_users_role ON users (role);

-- which learners each parent may see (set by the administrator)
CREATE TABLE IF NOT EXISTS parent_children (
  parent_id INT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  learner_id INT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  PRIMARY KEY (parent_id, learner_id)
);

CREATE TABLE IF NOT EXISTS lessons (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  lesson_key VARCHAR(60) NOT NULL UNIQUE,  -- i18n key of the lesson title, e.g. lesson_1 (lesson_term_work:<subject> for the rest)
  sort_order INT NOT NULL,
  subject_key VARCHAR(60) NULL             -- the subject the lesson belongs to
);

-- a learner's 7 subjects (two languages, a mathematics, Life Orientation and three more)
CREATE TABLE IF NOT EXISTS learner_subjects (
  learner_id INT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  subject_key VARCHAR(60) NOT NULL,
  PRIMARY KEY (learner_id, subject_key)
);

CREATE TABLE IF NOT EXISTS learner_lessons (
  learner_id INT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  lesson_id INT NOT NULL REFERENCES lessons(id) ON DELETE CASCADE,
  progress INT NOT NULL DEFAULT 0,
  done SMALLINT NOT NULL DEFAULT 0,
  assessment_viewed SMALLINT NOT NULL DEFAULT 0,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  PRIMARY KEY (learner_id, lesson_id)
);

-- the built-in multiple-choice check-in quiz; the latest attempt sets the learner's status
CREATE TABLE IF NOT EXISTS checkin_attempts (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  learner_id INT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  answers JSONB NOT NULL,           -- chosen option index per question
  score INT NOT NULL,
  total INT NOT NULL,
  feedback VARCHAR(500) NULL,       -- AI study tip, when AI was available
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_checkin_learner ON checkin_attempts (learner_id, created_at);

-- teacher-authored quizzes
CREATE TABLE IF NOT EXISTS quizzes (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  teacher_id INT NULL REFERENCES users(id) ON DELETE SET NULL,
  title VARCHAR(150) NOT NULL,
  grade VARCHAR(4) NOT NULL,
  subject_key VARCHAR(60) NOT NULL,
  time_limit_min INT NOT NULL DEFAULT 0,  -- 0 = untimed
  questions JSONB NOT NULL,               -- [{ "text": ..., "answer": ... }]
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_quizzes_grade ON quizzes (grade);

-- the learner's current attempt at each quiz (a retake starts it over); every submitted
-- attempt is also kept in quiz_submissions
CREATE TABLE IF NOT EXISTS quiz_attempts (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  quiz_id INT NOT NULL REFERENCES quizzes(id) ON DELETE CASCADE,
  learner_id INT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  answers JSONB NULL,
  score INT NULL,                   -- NULL while in progress
  total INT NOT NULL,
  timed_out SMALLINT NOT NULL DEFAULT 0,
  started_at TIMESTAMPTZ(3) NOT NULL,
  deadline TIMESTAMPTZ(3) NULL,     -- NULL for untimed quizzes
  submitted_at TIMESTAMPTZ(3) NULL,
  CONSTRAINT uq_attempt UNIQUE (quiz_id, learner_id)
);

-- every submitted attempt, retakes included, so teachers see the first score and not only the latest
CREATE TABLE IF NOT EXISTS quiz_submissions (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  quiz_id INT NOT NULL REFERENCES quizzes(id) ON DELETE CASCADE,
  learner_id INT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  answers JSONB NOT NULL,
  score INT NOT NULL,
  total INT NOT NULL,
  timed_out SMALLINT NOT NULL DEFAULT 0,
  started_at TIMESTAMPTZ(3) NOT NULL,
  submitted_at TIMESTAMPTZ(3) NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_submissions_quiz ON quiz_submissions (quiz_id, learner_id, id);

-- uploaded question papers; the file itself lives in UPLOAD_DIR under stored_name
CREATE TABLE IF NOT EXISTS papers (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  teacher_id INT NULL REFERENCES users(id) ON DELETE SET NULL,
  title VARCHAR(150) NOT NULL,
  grade VARCHAR(4) NOT NULL,
  subject_key VARCHAR(60) NOT NULL,
  file_name VARCHAR(255) NOT NULL,
  stored_name VARCHAR(100) NOT NULL,
  mime_type VARCHAR(100) NOT NULL,
  size_bytes INT NOT NULL,
  extracted_text TEXT NULL,         -- the file's text (OCR for photos and scans), read when a quiz is first made from it
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_papers_grade ON papers (grade);

-- classes (subject groups): one subject taught by one teacher to a group of learners, e.g.
-- 10A Mathematics, set up by the administrator. A teacher sees only their own classes, and a
-- learner gets only the quizzes and papers sent to the classes they are in.
CREATE TABLE IF NOT EXISTS classes (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(10) NOT NULL,        -- e.g. 10A
  grade VARCHAR(4) NOT NULL,
  subject_key VARCHAR(60) NOT NULL,
  teacher_id INT NULL REFERENCES users(id) ON DELETE SET NULL,  -- NULL until the administrator assigns one
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT uq_class UNIQUE (grade, name, subject_key)
);
CREATE INDEX IF NOT EXISTS idx_classes_teacher ON classes (teacher_id);

CREATE TABLE IF NOT EXISTS class_learners (
  class_id INT NOT NULL REFERENCES classes(id) ON DELETE CASCADE,
  learner_id INT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  PRIMARY KEY (class_id, learner_id)
);
CREATE INDEX IF NOT EXISTS idx_class_learners_learner ON class_learners (learner_id);

-- the classes each quiz and question paper was sent to
CREATE TABLE IF NOT EXISTS quiz_classes (
  quiz_id INT NOT NULL REFERENCES quizzes(id) ON DELETE CASCADE,
  class_id INT NOT NULL REFERENCES classes(id) ON DELETE CASCADE,
  PRIMARY KEY (quiz_id, class_id)
);
CREATE INDEX IF NOT EXISTS idx_quiz_classes_class ON quiz_classes (class_id);

CREATE TABLE IF NOT EXISTS paper_classes (
  paper_id INT NOT NULL REFERENCES papers(id) ON DELETE CASCADE,
  class_id INT NOT NULL REFERENCES classes(id) ON DELETE CASCADE,
  PRIMARY KEY (paper_id, class_id)
);
CREATE INDEX IF NOT EXISTS idx_paper_classes_class ON paper_classes (class_id);

-- learner_id is NULL for anonymous (imported) ratings; NULLs never clash on the unique key
CREATE TABLE IF NOT EXISTS teacher_ratings (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  teacher_id INT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  learner_id INT NULL REFERENCES users(id) ON DELETE CASCADE,
  rating SMALLINT NOT NULL,         -- 1 to 5 stars
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT uq_rating UNIQUE (teacher_id, learner_id)
);

-- the principal's feedback to a teacher
CREATE TABLE IF NOT EXISTS teacher_feedback (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  teacher_id INT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  from_user_id INT NULL REFERENCES users(id) ON DELETE SET NULL,
  message TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- HOD department reports sent to the principal
CREATE TABLE IF NOT EXISTS dept_reports (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  hod_id INT NULL REFERENCES users(id) ON DELETE SET NULL,
  dept VARCHAR(30) NOT NULL,
  "rows" JSONB NOT NULL,            -- [{ teacherId, name, subjectKey, gradeKey, attendance, performance, avgRating }]
  sent_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- msg_key + params for i18n-keyed messages the UI translates, message for server-written text
CREATE TABLE IF NOT EXISTS notifications (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  msg_key VARCHAR(60) NULL,
  params JSONB NULL,
  message VARCHAR(500) NULL,
  is_read SMALLINT NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_notifications_user ON notifications (user_id, created_at);

-- per-subject attendance and performance on the admin overview
CREATE TABLE IF NOT EXISTS subject_stats (
  subject_key VARCHAR(60) PRIMARY KEY,
  attendance INT NOT NULL,
  performance INT NOT NULL
);

-- forgot-password links; only a SHA-256 of the token is stored
CREATE TABLE IF NOT EXISTS password_resets (
  token_hash CHAR(64) PRIMARY KEY,
  user_id INT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  expires_at TIMESTAMPTZ NOT NULL
);

-- two-step sign-in for staff: after the right password, a 6-digit code is emailed. The browser
-- holds the random challenge (only its hash is stored). Asking again within the 10 minutes
-- emails the same code, so every code email from that time works.
CREATE TABLE IF NOT EXISTS login_codes (
  user_id INT PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,  -- one code at a time per account
  challenge_hash CHAR(64) NOT NULL UNIQUE,
  seed CHAR(32) NOT NULL,           -- the code is worked out from this and JWT_SECRET, so it can be emailed again unchanged
  attempts INT NOT NULL DEFAULT 0,
  expires_at TIMESTAMPTZ NOT NULL
);

-- the devices each account has signed in from: a sign-in from a new one emails a login alert
CREATE TABLE IF NOT EXISTS known_devices (
  user_id INT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  device_hash CHAR(64) NOT NULL,    -- hash of the app's device id (or of the browser's user agent)
  label VARCHAR(80) NULL,           -- e.g. "Chrome on Windows"
  first_seen TIMESTAMPTZ NOT NULL DEFAULT now(),
  last_seen TIMESTAMPTZ NOT NULL DEFAULT now(),
  PRIMARY KEY (user_id, device_hash)
);

-- the security log the administrator reads: sign-ins, failed sign-ins, lockouts, password
-- changes and account changes. Rows outlive the account (the name is kept as it was).
CREATE TABLE IF NOT EXISTS security_events (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  event VARCHAR(40) NOT NULL,
  user_id INT NULL REFERENCES users(id) ON DELETE SET NULL,   -- the account it is about, when known
  user_name VARCHAR(100) NULL,
  login VARCHAR(254) NULL,          -- what was typed in the login box (for failed sign-ins)
  actor_id INT NULL REFERENCES users(id) ON DELETE SET NULL,  -- who did it, when it was another person (an administrator)
  ip VARCHAR(64) NULL,
  user_agent VARCHAR(255) NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_security_events_time ON security_events (created_at);

-- online lessons a teacher schedules for one of their classes, held in the app's own live
-- classroom (video, audio and chat)
CREATE TABLE IF NOT EXISTS online_classes (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  class_id INT NOT NULL REFERENCES classes(id) ON DELETE CASCADE,
  teacher_id INT NULL REFERENCES users(id) ON DELETE SET NULL,
  title VARCHAR(150) NOT NULL,
  starts_at TIMESTAMPTZ NOT NULL,
  duration_min INT NOT NULL,
  ended_at TIMESTAMPTZ NULL,        -- set when the teacher ends the class early
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_online_classes_class ON online_classes (class_id, starts_at);
CREATE INDEX IF NOT EXISTS idx_online_classes_teacher ON online_classes (teacher_id, starts_at);

-- the class register: a row once a learner enters the live classroom, or once the teacher
-- marks them. A learner with no row did not attend.
CREATE TABLE IF NOT EXISTS online_attendance (
  online_class_id INT NOT NULL REFERENCES online_classes(id) ON DELETE CASCADE,
  learner_id INT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  status VARCHAR(10) NOT NULL CHECK (status IN ('present','late','absent')),
  joined_at TIMESTAMPTZ NULL,       -- when the learner first entered the classroom
  last_joined_at TIMESTAMPTZ NULL,  -- start of the learner's current visit, NULL while they are out
  seconds_attended INT NOT NULL DEFAULT 0,  -- time in the classroom over all visits
  marked_by VARCHAR(10) NOT NULL CHECK (marked_by IN ('join','teacher')),
  PRIMARY KEY (online_class_id, learner_id)
);
CREATE INDEX IF NOT EXISTS idx_online_attendance_learner ON online_attendance (learner_id);
